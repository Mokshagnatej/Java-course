package Loops;

public class while_loop {
    public static void main(String[] args) {
        int i = 1;

        while (i <= 5) {
            System.out.println("Honey"+" "+ i);
            int j = 1;
            while(j<=1){
                System.out.println("Reddy"+" "+j);
                j++;
            }
            i++;
        }
    }
}
