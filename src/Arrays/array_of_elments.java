package Arrays;

public class array_of_elments {
    public static void main(String[]args){
        int nums[] = new int[4];
        nums[0] = 18;
        nums[1] = 32;
        nums[2] = 42;
        nums[3] = 13;

        for(int i=0;i<4;i++){
            System.out.println(nums[i]);
        }
    }
}
